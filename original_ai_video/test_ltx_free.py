#!/usr/bin/env python3
"""Try creating genuinely AI-generated original moving video through free public LTX 2.5 ZeroGPU.
No Google account, no paid credentials, no third party footage, no slideshow.
The public inference quota may deny requests; never claim success without a verified MP4.
"""
import json, os, shutil, traceback
from pathlib import Path
from gradio_client import Client

SPACE="Lightricks/LTX-2.5"
report={"space":SPACE,"auth":"unauthenticated","intent":"Original text-to-video generated by diffusion model","successful_video":False}
Path("ai_video_probe_report.json").write_text(json.dumps(report,indent=2))
try:
    print("Connecting to public LTX ZeroGPU API...",flush=True)
    client=Client(SPACE, httpx_kwargs={"timeout":30.0})
    api=client.view_api(return_format="dict")
    Path("ai_video_api.json").write_text(json.dumps(api,indent=2,default=str))
    print("API endpoints:",json.dumps(api,default=str)[:3500],flush=True)
    named=(api.get("named_endpoints") or {})
    # The public generate button is bound to function run(prompt,image_path,height,width,duration_s,seed,decoder,auto_len,randomize_seed,do_enhance)
    endpoint=None
    for name, spec in named.items():
        if "run" in str(name).lower() or "predict" in str(name).lower():
            params=spec.get("parameters") or []
            if len(params)>=8:
                endpoint=name;break
    if not endpoint:
        for name,spec in named.items():
            if len(spec.get("parameters",[]))>=9:
                endpoint=name;break
    report["endpoint"]=endpoint
    if not endpoint:
        report["error"]="No verified public generation endpoint from Space API"
        raise RuntimeError(report["error"])
    print("Selected endpoint: "+endpoint,flush=True)
    prompt=("Cinematic close-up, a completely imaginary tiny teal robot with gold eyes "
            "walks through a luminous miniature forest made of glass, glowing leaves "
            "sway as it gently waves its hand, realistic smooth continuous movement, "
            "tracking shot, shallow depth of field, vertical frame, no text, no logos.")
    print("Generating fresh original AI motion, no input image...",flush=True)
    result=client.predict(prompt,None,896,512,2.0,42,"conv",False,False,False,api_name=endpoint)
    print("RESULT TYPE",str(result)[:1800],flush=True)
    import os
    path=None
    if isinstance(result,(list,tuple)):
        v=result[0]
        if isinstance(v,dict):path=v.get("video") or v.get("path") or v.get("name")
        if isinstance(v,str):path=v
    elif isinstance(result,str):path=result
    if not path or not Path(path).is_file():
        raise RuntimeError("Generated result not a local video file: "+str(result)[:800])
    raw=Path(path)
    if raw.stat().st_size<50000:
        raise RuntimeError("Video output too small")
    output=Path("original-ai-motion-test.mp4")
    shutil.copyfile(raw,output)
    report["successful_video"]=True
    report["bytes"]=output.stat().st_size
    report["output"]=str(output)
except Exception as exc:
    report["error"]=str(exc)
    report["traceback"]=traceback.format_exc()[-2000:]
    print("GENERATION FAILED OR BLOCKED: "+str(exc),flush=True)
finally:
    Path("ai_video_probe_report.json").write_text(json.dumps(report,indent=2,ensure_ascii=False))
    print(json.dumps(report,ensure_ascii=False,indent=2),flush=True)
if not report["successful_video"]:
    raise SystemExit(2)
